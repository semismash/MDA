#!/usr/bin/env python3
"""gen_synth.py: convert the SystemVerilog sources of rtl.f into one plain Verilog file for synthesis, src/mda_synth.v.

Why: the Yosys front end that Tiny Tapeout's tools use cannot read package imports or ports typed with package typedefs, which
is how the RTL is written. sv2v resolves packages and typedefs and writes plain Verilog. The SystemVerilog stays the source of
truth (lint, tests, the interpreter in verif/); the generated file is what info.yaml lists and what CI synthesizes. The macro
variant of the memories is selected (-D MDA_SRAM_MACRO), so the macro instances are in the generated file.

  python3 tools/gen_synth.py             regenerate src/mda_synth.v (needs sv2v on PATH, or --sv2v PATH)
  python3 tools/gen_synth.py --check     exit 1 if src/mda_synth.v is stale compared with the sources (no sv2v needed)
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'src', 'mda_synth.v')
DEFINES = ['MDA_SRAM_MACRO']
TAG = '// sources-sha256: '


def sources():
    """SystemVerilog files of rtl.f in order (the asic-only macro stubs are Verilog already and stay separate)."""
    files = []
    for line in open(os.path.join(ROOT, 'rtl.f')):
        raw = line.strip()
        if not raw or raw.startswith('#') or '# asic-only' in raw:
            continue
        files.append(raw.split('#')[0].strip())
    return files


def digest(files):
    h = hashlib.sha256()
    for f in files:
        data = open(os.path.join(ROOT, f), 'rb').read().replace(b'\r\n', b'\n')
        h.update(f.encode() + b'\0' + data + b'\0')
    h.update(('defines:' + ','.join(DEFINES)).encode())
    return h.hexdigest()


def stored_digest():
    if not os.path.isfile(OUT):
        return None
    for line in open(OUT, errors='replace'):
        if line.startswith(TAG):
            return line[len(TAG):].strip()
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--sv2v', default=None, help='path to the sv2v executable (default: sv2v on PATH)')
    a = ap.parse_args()
    files = sources()
    want = digest(files)
    if a.check:
        have = stored_digest()
        if have == want:
            print('src/mda_synth.v is up to date')
            return 0
        print('src/mda_synth.v is ' + ('missing' if not os.path.isfile(OUT) else 'STALE') + ': run python3 tools/gen_synth.py')
        return 1
    exe = a.sv2v or shutil.which('sv2v')
    if not exe:
        sys.exit('sv2v not found: put sv2v on PATH or pass --sv2v PATH (releases: github.com/zachjs/sv2v)')
    cmd = [exe] + ['--define=' + d for d in DEFINES] + files
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit('sv2v failed (see above)')
    ver = subprocess.run([exe, '--version'], capture_output=True, text=True).stdout.strip() or 'unknown'
    header = ('// Generated by tools/gen_synth.py with sv2v. DO NOT EDIT: change the SystemVerilog sources and regenerate.\n'
              f'// sv2v version: {ver}\n// defines: {", ".join(DEFINES)}\n// sources: {len(files)} files from rtl.f\n{TAG}{want}\n\n')
    body = r.stdout.replace('\r\n', '\n')
    if not body.endswith('\n'):
        body += '\n'
    open(OUT, 'w', newline='\n').write(header + body)
    print(f'wrote src/mda_synth.v ({len(body.splitlines())} lines, from {len(files)} SystemVerilog files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())